def assign_region(username: str) -> str:
    digest = hashlib.sha256(username.strip().lower().encode("utf-8")).hexdigest()
    return REGIONS[int(digest, 16) % len(REGIONS)]


def main() -> None:
    if len(sys.argv) != 2:
        print("Использование: python data/assign_region.py YOUR_GITHUB_USERNAME")
        sys.exit(1)
    username = sys.argv[1].strip()
    if not username:
        print("Укажите непустой GitHub username.")
        sys.exit(1)
    region = assign_region(username)
    print(f"GitHub username: {username}")
    print(f"Ваш регион:      {region}")
    print("Скачайте выгрузку региона: https://dtp-stat.ru/opendata/")


if __name__ == "__main__":
    main()
